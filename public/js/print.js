import { h, clear, $, money } from './dom.js';

const SLOT = { morning: 'Morning', afternoon: 'Afternoon', evening: 'Evening', any: 'Anytime' };
const TIER = { budget: 'Affordable', comfort: 'Comfort', premium: 'Premium' };

function fmtDate(iso) {
  const [y, m, d] = iso.split('-').map(Number);
  return new Date(Date.UTC(y, m - 1, d)).toLocaleDateString('en-IN', { weekday: 'short', day: 'numeric', month: 'short', year: 'numeric', timeZone: 'UTC' });
}

/**
 * Builds a print-only, light-themed version of the (possibly customised) itinerary
 * and opens the browser's print dialog, where "Save as PDF" produces the file.
 */
export function printPlan(plan, days) {
  const root = clear($('#print-root'));
  const { destination: d, params: p, estimate: e, advice } = plan;
  const first = plan.itinerary[0]?.date;
  const last = plan.itinerary[plan.itinerary.length - 1]?.date;

  root.append(
    h(
      'header',
      { class: 'p-head' },
      h('div', { class: 'p-brand' }, 'Voyagr'),
      h('h1', {}, `${p.days} ${p.days === 1 ? 'day' : 'days'} in ${d.name}`),
      h('p', {}, [d.region, first ? `${fmtDate(first)}${last && last !== first ? ` – ${fmtDate(last)}` : ''}` : null, `${p.travelers} traveller${p.travelers > 1 ? 's' : ''}`, TIER[p.budget]].filter(Boolean).join(' · '))
    ),
    h(
      'table',
      { class: 'p-costs' },
      h('tr', {}, ['Stay', 'Food', 'Local transport', 'Entry fees', 'Estimated total'].map((x) => h('th', {}, x))),
      h('tr', {}, [e.stay, e.food, e.localTransport, e.entryFees, e.total].map((x) => h('td', {}, money(x))))
    )
  );

  days.forEach((day, i) => {
    const base = plan.itinerary[i];
    root.append(
      h(
        'section',
        { class: 'p-day' },
        h('h2', {}, `Day ${i + 1}${base?.date ? ` · ${fmtDate(base.date)}` : ''}`),
        base?.sun ? h('p', { class: 'p-muted' }, `Sunrise ${base.sun.sunrise} · Sunset ${base.sun.sunset}`) : null,
        day.note ? h('p', { class: 'p-note' }, day.note) : null,
        day.stops.length
          ? h(
              'ol',
              {},
              day.stops.map((s) =>
                h(
                  'li',
                  {},
                  h('strong', {}, s.name),
                  s.slot ? h('span', { class: 'p-muted' }, ` — ${SLOT[s.slot] || ''}`) : null,
                  s.area ? h('span', { class: 'p-muted' }, ` · ${s.area}`) : null,
                  (() => {
                    const useful = (v) => v && !/^check locally$/i.test(v);
                    const bits = [useful(s.hours) && `Hours: ${s.hours}`, useful(s.fee) && `Entry: ${s.fee}`].filter(Boolean);
                    return bits.length ? h('div', { class: 'p-muted' }, bits.join(' · ')) : null;
                  })(),
                  s.note ? h('div', { class: 'p-note' }, s.note) : null
                )
              )
            )
          : h('p', {}, base?.note || 'Free day to explore.'),
        base?.meals
          ? h(
              'p',
              { class: 'p-meals' },
              ['lunch', 'dinner']
                .map((k) => {
                  const r = base.meals[k];
                  if (!r) return null;
                  return `${k === 'lunch' ? 'Lunch' : 'Dinner'}: ${r.name}${r.hoursThatDay ? ` (${r.hoursThatDay})` : ''}`;
                })
                .filter(Boolean)
                .join('   ·   ')
            )
          : null
      )
    );
  });

  if (advice) {
    root.append(
      h(
        'section',
        { class: 'p-advice' },
        h('h2', {}, 'Before you go'),
        advice.summary ? h('p', {}, advice.summary) : null,
        advice.alerts.length ? h('div', {}, h('h3', {}, 'Important'), h('ul', {}, advice.alerts.map((a) => h('li', {}, a)))) : null,
        h('h3', {}, 'Pack'),
        h('ul', { class: 'p-cols' }, advice.pack.map((x) => h('li', {}, x.text))),
        h('h3', {}, 'Do'),
        h('ul', {}, advice.dos.map((x) => h('li', {}, x))),
        h('h3', {}, 'Don’t'),
        h('ul', {}, advice.donts.map((x) => h('li', {}, x))),
        h('p', {}, `Emergency: ${advice.emergency.map((x) => `${x.label} ${x.number}`).join(' · ')}`)
      )
    );
  }

  root.append(
    h(
      'section',
      { class: 'p-advice' },
      h('h2', {}, 'Getting there'),
      h('ul', {}, plan.transport.reach.map((r) => h('li', {}, `${r.mode}: ${r.hub}${r.distanceKm ? ` (${r.distanceKm} km)` : ''}`)))
    ),
    h('footer', { class: 'p-foot' }, `${plan.disclaimer} Generated by Voyagr on ${new Date().toLocaleDateString('en-IN')}.`)
  );

  const prevTitle = document.title;
  // Most browsers use the page title as the suggested PDF file name.
  document.title = `Voyagr - ${p.days} days in ${d.name}`;
  const restore = () => {
    document.title = prevTitle;
    window.removeEventListener('afterprint', restore);
  };
  window.addEventListener('afterprint', restore);
  window.print();
  setTimeout(restore, 3000);
}
